// Generate src/catsSchedule.ts from probed media durations (fps 30 frame math).
// Run: node scripts/probe-schedule.mjs   (check: node scripts/check-schedule.mjs)
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";

const ROOT = new URL("..", import.meta.url).pathname;
const FPS = 30, GAP_F = 4, TAIL_F = 9, NCLIP = 6, NSLIDE = 18;

const dur = (f) => parseFloat(execFileSync("ffprobe",
  ["-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", f],
  { encoding: "utf8" }).trim());

// clips: 6 VO files, back-to-back with a 4-frame gap, 9-frame tail after the last
const durSec = Array.from({ length: NCLIP }, (_, k) => dur(`${ROOT}public/vo/cats-0${k + 1}.mp3`));
const CLIP_DUR_F = durSec.map((d) => Math.round(d * FPS));
const CLIP_START_F = CLIP_DUR_F.reduce((acc, d, k) => {
  acc.push(k === 0 ? 0 : acc[k - 1] + CLIP_DUR_F[k - 1] + GAP_F);
  return acc;
}, []);
const VO_AUDIO_F = durSec.map((d) => Math.ceil((d + 0.05) * FPS));
const TOTAL_F = CLIP_START_F[NCLIP - 1] + CLIP_DUR_F[NCLIP - 1] + TAIL_F;

// 18 slides = 6 clips x 3 slots; slot k splits the clip window in 3
const SLIDE_START_F = [], SLIDE_DUR_F = [];
for (let k = 0; k < NCLIP; k++) {
  const b = [0, 1, 2].map((j) => CLIP_START_F[k] + Math.round(j * CLIP_DUR_F[k] / 3));
  const end = CLIP_START_F[k] + CLIP_DUR_F[k];
  b.forEach((s, j) => {
    SLIDE_START_F.push(s);
    SLIDE_DUR_F.push((j === 2 ? end : b[j + 1]) - s);
  });
}

// SFX slots: pad to real media + 0.05s; chime starts so it ends exactly at root end
const sfxPad = (f) => Math.ceil((dur(`${ROOT}public/sfx/${f}`) + 0.05) * FPS);
const STAMP_FRAMES = sfxPad("hook-stamp.wav");
const WHOOSH_FRAMES = sfxPad("whoosh.wav");
const CHIME_AUDIO_F = sfxPad("seam-chime.wav");

const out = `// GENERATED by scripts/probe-schedule.mjs — do not edit by hand.
// Frame constants at fps 30. Re-run the script after changing any VO/SFX asset.
export const FPS = ${FPS};
export const GAP_F = ${GAP_F};
export const TAIL_F = ${TAIL_F};
export const TR_F = 7;
export const TITLE_F = 36;
export const CLIP_START_F = [${CLIP_START_F.join(", ")}];
export const CLIP_DUR_F = [${CLIP_DUR_F.join(", ")}];
export const VO_AUDIO_F = [${VO_AUDIO_F.join(", ")}];
export const SLIDE_START_F = [${SLIDE_START_F.join(", ")}];
export const SLIDE_DUR_F = [${SLIDE_DUR_F.join(", ")}];
export const STAMP_START_F = 0;
export const STAMP_FRAMES = ${STAMP_FRAMES};
export const WHOOSH_START_F = [${CLIP_START_F.slice(1).join(", ")}];
export const WHOOSH_FRAMES = ${WHOOSH_FRAMES};
export const CHIME_AUDIO_F = ${CHIME_AUDIO_F};
export const CHIME_START_F = ${TOTAL_F - CHIME_AUDIO_F};
export const TOTAL_F = ${TOTAL_F};
`;
writeFileSync(ROOT + "src/catsSchedule.ts", out);
console.log(`catsSchedule.ts written: TOTAL_F=${TOTAL_F} (${(TOTAL_F / FPS).toFixed(3)}s) clips=[${CLIP_DUR_F}]`);
